// =============================================================================
// VedaDB Server - Unified Configuration Generator
// =============================================================================
// Description:
//   A Go utility that generates OS-appropriate config.yaml files for VedaDB
//   Server. Used by all platform installers (Windows MSI, macOS PKG, Linux DEB)
//   to create consistent, sensible default configurations.
//
// Usage:
//   config-generator [flags]
//
// Flags:
//   --os string          Target OS: windows, darwin, linux (required)
//   --data-dir string    Data directory path (auto-detected per OS)
//   --log-dir string     Log directory path (auto-detected per OS)
//   --port int           Server listen port (default: 7480)
//   --bind string        Bind address (default: 0.0.0.0)
//   --admin-user string  Admin username (default: admin)
//   --admin-pass string  Admin password (auto-generated if not set)
//   --auth-enabled       Enable authentication (default: true)
//   --cache-size string  Cache size (default: 512MB)
//   --output string      Output file path (default: stdout)
//   --version            Show version information
//
// Examples:
//   # Generate default config for Linux
//   config-generator --os linux --output /etc/vedadb/config.yaml
//
//   # Generate with custom port and data directory
//   config-generator --os windows --port 9000 --data-dir D:\VedaDB\Data
//
//   # Generate for macOS with custom settings
//   config-generator --os darwin --port 8080 --bind 127.0.0.1
// =============================================================================

package main

import (
	"crypto/rand"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"time"
)

// InstallerVersion is set at build time
var InstallerVersion = "1.0.0"

// =============================================================================
// OS-Specific Defaults
// =============================================================================

type OSDefaults struct {
	DataDir       string
	LogDir        string
	ConfigPath    string
	ServiceName   string
	ServiceUser   string
	ServiceGroup  string
	BindAddress   string
	MaxOpenFiles  int
}

func getOSDefaults(os string) OSDefaults {
	switch os {
	case "windows":
		return OSDefaults{
			DataDir:      `C:\ProgramData\VedaDB\data`,
			LogDir:       `C:\ProgramData\VedaDB\logs`,
			ConfigPath:   `C:\ProgramData\VedaDB\config.yaml`,
			ServiceName:  "VedaDBServer",
			ServiceUser:  `NT AUTHORITY\NetworkService`,
			ServiceGroup: "",
			BindAddress:  "0.0.0.0",
			MaxOpenFiles: 65536,
		}
	case "darwin":
		return OSDefaults{
			DataDir:      "/usr/local/var/vedadb/data",
			LogDir:       "/usr/local/var/vedadb/logs",
			ConfigPath:   "/opt/vedadb/etc/config.yaml",
			ServiceName:  "io.vedadb.server",
			ServiceUser:  "_vedadb",
			ServiceGroup: "_vedadb",
			BindAddress:  "127.0.0.1", // macOS: localhost by default for security
			MaxOpenFiles: 65536,
		}
	case "linux":
		return OSDefaults{
			DataDir:      "/var/lib/vedadb/data",
			LogDir:       "/var/log/vedadb",
			ConfigPath:   "/etc/vedadb/config.yaml",
			ServiceName:  "vedadb",
			ServiceUser:  "vedadb",
			ServiceGroup: "vedadb",
			BindAddress:  "0.0.0.0",
			MaxOpenFiles: 65536,
		}
	default:
		// Return Linux defaults as fallback
		return getOSDefaults("linux")
	}
}

// =============================================================================
// Password Generation
// =============================================================================

// generatePassword creates a cryptographically secure random password.
func generatePassword(length int) string {
	const charset = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*"
	b := make([]byte, length)
	rand.Read(b)
	for i := range b {
		b[i] = charset[int(b[i])%len(charset)]
	}
	return string(b)
}

// generatePasswordHash creates a bcrypt hash of the password.
// Note: This is a placeholder. In production, use golang.org/x/crypto/bcrypt
func generatePasswordHash(password string) string {
	// Placeholder hash format - real implementation would use bcrypt
	// For now, we store the hash prefix to indicate it's auto-generated
	return fmt.Sprintf("$2a$10$[AUTO_GENERATED_PASSWORD:%s]", password)
}

