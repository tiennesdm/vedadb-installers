// =============================================================================
// Config Data
// =============================================================================

type ConfigData struct {
	Version           string
	Timestamp         string
	OS                string
	Arch              string
	Port              int
	BindAddress       string
	DataDir           string
	LogDir            string
	MaxOpenFiles      int
	AuthEnabled       bool
	AdminUser         string
	AdminPassword     string
	AdminPasswordHash string
	CacheSize         string
	ServiceName       string
	ServiceUser       string
	ServiceGroup      string
}

// =============================================================================
// Config Generation
// =============================================================================

func generateConfig(data *ConfigData) string {
	config := configTemplate

	// Simple template substitution (no external dependencies)
	replacements := map[string]string{
		"{{.Version}}":           data.Version,
		"{{.Timestamp}}":         data.Timestamp,
		"{{.OS}}":                data.OS,
		"{{.Arch}}":              data.Arch,
		"{{.Port}}":              fmt.Sprintf("%d", data.Port),
		"{{.BindAddress}}":       data.BindAddress,
		"{{.DataDir}}":           data.DataDir,
		"{{.LogDir}}":            data.LogDir,
		"{{.MaxOpenFiles}}":      fmt.Sprintf("%d", data.MaxOpenFiles),
		"{{.AuthEnabled}}":       fmt.Sprintf("%t", data.AuthEnabled),
		"{{.AdminUser}}":         data.AdminUser,
		"{{.AdminPassword}}":     data.AdminPassword,
		"{{.AdminPasswordHash}}": data.AdminPasswordHash,
		"{{.CacheSize}}":         data.CacheSize,
		"{{.ServiceName}}":       data.ServiceName,
		"{{.ServiceUser}}":       data.ServiceUser,
		"{{.ServiceGroup}}":      data.ServiceGroup,
	}

	result := config
	for key, value := range replacements {
		result = strings.ReplaceAll(result, key, value)
	}

	// Handle conditional service group
	if data.ServiceGroup == "" {
		result = strings.ReplaceAll(result, "  group: \n", "")
	}

	return result
}

// =============================================================================
// Main
// =============================================================================

func main() {
	var (
		osFlag        = flag.String("os", "", "Target OS: windows, darwin, linux (detected automatically if not set)")
		dataDirFlag   = flag.String("data-dir", "", "Data directory path (auto-detected per OS if not set)")
		logDirFlag    = flag.String("log-dir", "", "Log directory path (auto-detected per OS if not set)")
		portFlag      = flag.Int("port", 7480, "Server listen port")
		bindFlag      = flag.String("bind", "", "Bind address (auto-detected per OS if not set)")
		adminUserFlag = flag.String("admin-user", "admin", "Admin username")
		adminPassFlag = flag.String("admin-pass", "", "Admin password (auto-generated if not set)")
		authEnabled   = flag.Bool("auth-enabled", true, "Enable authentication")
		cacheSizeFlag = flag.String("cache-size", "512MB", "Cache size")
		outputFlag    = flag.String("output", "", "Output file path (stdout if not set)")
		showVersion   = flag.Bool("version", false, "Show version and exit")
	)

	flag.Usage = func() {
		fmt.Fprintf(os.Stderr, "VedaDB Configuration Generator v%s\n\n", InstallerVersion)
		fmt.Fprintf(os.Stderr, "Usage: %s [options]\n\n", os.Args[0])
		fmt.Fprintf(os.Stderr, "Generates OS-appropriate config.yaml for VedaDB Server.\n\n")
		fmt.Fprintf(os.Stderr, "Options:\n")
		flag.PrintDefaults()
		fmt.Fprintf(os.Stderr, "\nExamples:\n")
		fmt.Fprintf(os.Stderr, "  %s --os linux --output /etc/vedadb/config.yaml\n", os.Args[0])
		fmt.Fprintf(os.Stderr, "  %s --os windows --port 9000 --data-dir D:\\VedaDB\\Data\n", os.Args[0])
		fmt.Fprintf(os.Stderr, "  %s --os darwin --bind 127.0.0.1\n", os.Args[0])
	}

	flag.Parse()

	// Show version
	if *showVersion {
		fmt.Printf("VedaDB Config Generator v%s\n", InstallerVersion)
		fmt.Printf("Built for: %s/%s\n", runtime.GOOS, runtime.GOARCH)
		os.Exit(0)
	}

	// Detect OS
	targetOS := *osFlag
	if targetOS == "" {
		targetOS = runtime.GOOS
		if targetOS == "darwin" {
			targetOS = "darwin"
		}
	}

	// Normalize OS name
	switch targetOS {
	case "windows", "win32", "win64":
		targetOS = "windows"
	case "darwin", "macos", "osx":
		targetOS = "darwin"
	case "linux":
		targetOS = "linux"
	default:
		fmt.Fprintf(os.Stderr, "Error: Unsupported OS '%s'. Use: windows, darwin, linux\n", targetOS)
		os.Exit(1)
	}

	// Get OS defaults
	defaults := getOSDefaults(targetOS)

	// Determine paths
	dataDir := *dataDirFlag
	if dataDir == "" {
		dataDir = defaults.DataDir
	}

	logDir := *logDirFlag
	if logDir == "" {
		logDir = defaults.LogDir
	}

	bindAddr := *bindFlag
	if bindAddr == "" {
		bindAddr = defaults.BindAddress
	}

	// Generate password
	adminPassword := *adminPassFlag
	if adminPassword == "" {
		adminPassword = generatePassword(16)
	}
	adminPasswordHash := generatePasswordHash(adminPassword)

	// Build config data
	configData := &ConfigData{
		Version:           InstallerVersion,
		Timestamp:         time.Now().UTC().Format(time.RFC3339),
		OS:                targetOS,
		Arch:              runtime.GOARCH,
		Port:              *portFlag,
		BindAddress:       bindAddr,
		DataDir:           filepath.ToSlash(dataDir),
		LogDir:            filepath.ToSlash(logDir),
		MaxOpenFiles:      defaults.MaxOpenFiles,
		AuthEnabled:       *authEnabled,
		AdminUser:         *adminUserFlag,
		AdminPassword:     adminPassword,
		AdminPasswordHash: adminPasswordHash,
		CacheSize:         *cacheSizeFlag,
		ServiceName:       defaults.ServiceName,
		ServiceUser:       defaults.ServiceUser,
		ServiceGroup:      defaults.ServiceGroup,
	}

	// Generate configuration
	config := generateConfig(configData)

	// Write output
	outputPath := *outputFlag
	if outputPath == "" {
		// Print to stdout
		fmt.Println(config)
	} else {
		// Create parent directory if needed
		dir := filepath.Dir(outputPath)
		if err := os.MkdirAll(dir, 0750); err != nil {
			fmt.Fprintf(os.Stderr, "Error: Failed to create directory %s: %v\n", dir, err)
			os.Exit(1)
		}

		if err := os.WriteFile(outputPath, []byte(config), 0640); err != nil {
			fmt.Fprintf(os.Stderr, "Error: Failed to write config: %v\n", err)
			os.Exit(1)
		}

		fmt.Printf("Configuration written to: %s\n", outputPath)
		fmt.Printf("Admin password (auto-generated): %s\n", adminPassword)
		fmt.Printf("Remember to change this password after first login!\n")
	}
}
